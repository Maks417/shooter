"""Generate the map registry from Content/Maps/*.map.json (ADR-083).

One definition file per map: identity, display copy, approved seed, recipe generator, planner (an inline arena layout
document or a named C# planner) and presentation hints. Writes
UnityProject/Assets/Shooter/Generation/Core/Environment/MapRegistry.g.cs (+ deterministic .meta).

Usage:
  python Tools/generate_map_registry.py           # validate and (re)write
  python Tools/generate_map_registry.py --check   # validate and fail when the generated file is stale
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFINITIONS = Path("Content/Maps")
ASSETS = Path("UnityProject/Assets/Shooter")
OUT = ASSETS / "Generation/Core/Environment/MapRegistry.g.cs"
REGISTRY_SOURCE = ASSETS / "Generation/Core/Environment/MapRegistry.cs"
SCHEMA_ID = "shooter.map-definition.v1"
ID_PATTERN = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
TEXT_PATTERN = re.compile(r"^[ -~]{1,120}$")
# Frozen per-map recipe generators stay bound to their map; new maps use the generic map.arena recipe.
LEGACY_RECIPES = {"map.compound": "training-compound", "map.depot": "depot-yard", "map.oil": "oil-depot"}
RECIPES = set(LEGACY_RECIPES) | {"map.arena"}
SKIES = {"default", "compound", "dusty-yard", "petroleum"}
GROUNDS = {"soil", "asphalt"}
TOP_KEYS = ["schemaId", "id", "order", "displayName", "description", "seed", "recipe", "planner", "presentation"]

HEADER = ("// <auto-generated>\n// Generated by Tools/generate_map_registry.py from Content/Maps/*.map.json (ADR-083).\n"
          "// Do not edit by hand: change the definition file and rerun the generator.\n// </auto-generated>\n")
META = ("fileFormatVersion: 2\nguid: {guid}\nMonoImporter:\n  externalObjects: {{}}\n  serializedVersion: 2\n"
        "  defaultReferences: []\n  executionOrder: 0\n  icon: {{instanceID: 0}}\n  userData: \n"
        "  assetBundleName: \n  assetBundleVariant: \n")


class DefinitionError(ValueError):
    pass


def code_planners(root: Path) -> set:
    text = (root / REGISTRY_SOURCE).read_text(encoding="utf-8")
    block = re.search(r"CodePlanners\s*=.*?\{(.*?)\};", text, re.S)
    if not block:
        raise DefinitionError("CodePlanners table not found in " + str(REGISTRY_SOURCE))
    return set(re.findall(r'\["([a-z0-9-]+)"\]', block.group(1)))


def no_duplicates(where):
    def hook(pairs):
        seen = {}
        for key, value in pairs:
            if key in seen:
                raise DefinitionError(where + ": duplicate key " + key)
            seen[key] = value
        return seen
    return hook


def validate(root: Path, path: Path, doc, planners) -> dict:
    where = path.relative_to(root).as_posix()
    if not isinstance(doc, dict):
        raise DefinitionError(where + ": expected an object")
    keys = set(doc)
    required = set(TOP_KEYS)
    missing = sorted(required - keys)
    unknown = sorted(keys - required - {"layout"})
    if missing or unknown:
        raise DefinitionError(where + ": missing " + ", ".join(missing) + " unknown " + ", ".join(unknown))
    if doc["schemaId"] != SCHEMA_ID:
        raise DefinitionError(where + ": schemaId must be " + SCHEMA_ID)
    map_id = doc["id"]
    if not isinstance(map_id, str) or not ID_PATTERN.match(map_id) or len(map_id) > 48:
        raise DefinitionError(where + ": id must be kebab-case (max 48)")
    if path.name != map_id + ".map.json":
        raise DefinitionError(where + ": file name must be " + map_id + ".map.json")
    order = doc["order"]
    if not isinstance(order, int) or isinstance(order, bool) or not 0 <= order <= 255:
        raise DefinitionError(where + ".order: integer 0..255")
    for name in ("displayName", "description"):
        if not isinstance(doc[name], str) or not TEXT_PATTERN.match(doc[name]) or '"' in doc[name] or "\\" in doc[name]:
            raise DefinitionError(where + "." + name + ": 1-120 printable ASCII characters without quotes or backslashes")
    seed = doc["seed"]
    if not isinstance(seed, str) or not re.match(r"^(0|[1-9][0-9]{0,19})$", seed) or int(seed) > 18446744073709551615:
        raise DefinitionError(where + ".seed: decimal string within ulong")
    recipe = doc["recipe"]
    if recipe not in RECIPES:
        raise DefinitionError(where + ".recipe: one of " + ", ".join(sorted(RECIPES)))
    if recipe in LEGACY_RECIPES and LEGACY_RECIPES[recipe] != map_id:
        raise DefinitionError(where + ".recipe: " + recipe + " is frozen to " + LEGACY_RECIPES[recipe] + "; new maps use map.arena")
    planner = doc["planner"]
    layout_json = None
    if planner == "layout":
        if "layout" not in doc or not isinstance(doc["layout"], dict):
            raise DefinitionError(where + ": planner layout needs a layout object")
        layout_json = json.dumps(doc["layout"], separators=(",", ":"), ensure_ascii=True)
    elif isinstance(planner, str) and planner.startswith("code:"):
        if planner[5:] not in planners:
            raise DefinitionError(where + ".planner: unknown code planner " + planner[5:] + " (known: " + ", ".join(sorted(planners)) + ")")
        if "layout" in doc:
            raise DefinitionError(where + ": a code planner takes no layout object")
    else:
        raise DefinitionError(where + ".planner: layout or code:<name>")
    presentation = doc["presentation"]
    if not isinstance(presentation, dict) or set(presentation) != {"sky", "groundSurface"}:
        raise DefinitionError(where + ".presentation: exactly sky and groundSurface")
    if presentation["sky"] not in SKIES:
        raise DefinitionError(where + ".presentation.sky: one of " + ", ".join(sorted(SKIES)))
    if presentation["groundSurface"] not in GROUNDS:
        raise DefinitionError(where + ".presentation.groundSurface: one of " + ", ".join(sorted(GROUNDS)))
    return {"source": where, "id": map_id, "order": order, "displayName": doc["displayName"], "description": doc["description"],
            "seed": seed, "recipe": recipe, "planner": planner, "layout": layout_json,
            "sky": presentation["sky"], "ground": presentation["groundSurface"]}


def load(root: Path) -> list:
    planners = code_planners(root)
    files = sorted((root / DEFINITIONS).glob("*.map.json"))
    if not files:
        raise DefinitionError("no map definitions under " + str(DEFINITIONS))
    maps = []
    for path in files:
        raw = path.read_bytes()
        if b"\r" in raw:
            raise DefinitionError(path.relative_to(root).as_posix() + ": expected LF line endings")
        try:
            doc = json.loads(raw.decode("utf-8"), object_pairs_hook=no_duplicates(path.name))
        except json.JSONDecodeError as error:
            raise DefinitionError(path.name + ": invalid JSON: " + str(error)) from error
        maps.append(validate(root, path, doc, planners))
    for attr in ("id", "order", "seed"):
        seen = {}
        for m in maps:
            if m[attr] in seen:
                raise DefinitionError(m["source"] + ": " + attr + " also used by " + seen[m[attr]])
            seen[m[attr]] = m["source"]
    return sorted(maps, key=lambda m: m["order"])


def cs(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(maps) -> str:
    rows = []
    for m in maps:
        rows.append("            // " + m["source"] + "\n"
                    "            new MapDefinition(" + cs(m["id"]) + ", " + str(m["order"]) + ", " + cs(m["displayName"]) + ",\n"
                    "                " + cs(m["description"]) + ",\n"
                    "                " + m["seed"] + "UL, " + cs(m["recipe"]) + ", " + cs(m["planner"]) + ",\n"
                    "                " + ("null" if m["layout"] is None else cs(m["layout"])) + ",\n"
                    "                " + cs(m["sky"]) + ", " + cs(m["ground"]) + ")")
    return (HEADER + "#nullable enable\n\nnamespace Shooter.Generation.Environment\n{\n"
            "    public static partial class MapRegistry\n    {\n"
            "        private static MapDefinition[] CreateGeneratedDefinitions() => new[]\n        {\n"
            + ",\n".join(rows) + "\n        };\n    }\n}\n")


def meta_for(relative: Path) -> str:
    return META.format(guid=hashlib.md5(("shooter.map-registry:" + relative.as_posix()).encode("ascii")).hexdigest())


def run(root: Path, check: bool) -> list:
    outputs = {OUT: render(load(root)), Path(str(OUT) + ".meta"): meta_for(OUT)}
    changed = []
    for relative, text in outputs.items():
        target = root / relative
        current = target.read_bytes().decode("utf-8") if target.is_file() else None
        if current == text:
            continue
        changed.append(relative.as_posix())
        if not check:
            target.write_bytes(text.encode("utf-8"))
    return changed


def main(argv) -> int:
    check = "--check" in argv[1:]
    if [a for a in argv[1:] if a != "--check"]:
        print("usage: python Tools/generate_map_registry.py [--check]", file=sys.stderr)
        return 2
    try:
        changed = run(ROOT, check)
    except DefinitionError as error:
        print("map definitions invalid: " + str(error), file=sys.stderr)
        return 1
    if check:
        if changed:
            print("generated map registry is stale; run python Tools/generate_map_registry.py:\n  " + "\n  ".join(changed), file=sys.stderr)
            return 1
        print("map registry up to date")
        return 0
    print("wrote " + str(len(changed)) + " file(s)" + "".join("\n  " + p for p in changed))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
