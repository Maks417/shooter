"""Reproducibly derive the vendored double-precision FastNoiseLite from the pinned upstream C# file (ADR-075 / T092).

Upstream FastNoiseLite computes in float. Unity's Mono and the .NET tools lane round intermediate float results
differently (observed ~1 ulp drift in OpenSimplex2), which breaks cross-lane content-hash determinism. IEEE double
+ - * / and sqrt are identical in both runtimes, so the vendored copy is a mechanical float->double port.

Usage:
  python Tools/port_fastnoiselite_double.py <upstream FastNoiseLite.cs>            # write the vendored file
  python Tools/port_fastnoiselite_double.py <upstream FastNoiseLite.cs> --check    # verify the vendored file

The upstream file is not committed; fetch tag v1.1.1 CSharp/FastNoiseLite.cs and its SHA-256 must match below.
"""
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "UnityProject/Assets/Shooter/Generation/Core/Noise/ThirdParty/FastNoiseLite.cs"
UPSTREAM_TAG = "v1.1.1"
UPSTREAM_SHA256 = "605090835008f4ef58fc39cdfa15df5051a4f5575d5e01fd7d355b9f67b0160e"
NAMESPACE = "Shooter.Generation.Noise.ThirdParty"

# Decimal float literals with an f suffix (2f, 0.5f, 1e-3f). The lookbehind keeps hex/identifier text untouched.
FLOAT_LITERAL = re.compile(r"(?<![0-9A-Za-z_.])([0-9]+(?:\.[0-9]+)?(?:[eE][-+]?[0-9]+)?)f\b")
FLOAT_KEYWORD = re.compile(r"\bfloat\b")


def port(upstream: bytes) -> bytes:
    if hashlib.sha256(upstream).hexdigest() != UPSTREAM_SHA256:
        raise ValueError("Upstream FastNoiseLite.cs does not match the pinned " + UPSTREAM_TAG + " SHA-256")
    text = upstream.decode("utf-8")
    if "\r" in text:
        raise ValueError("Expected LF upstream bytes")

    def once(source, old, new):
        if source.count(old) != 1:
            raise ValueError("Expected exactly one occurrence of: " + old.strip())
        return source.replace(old, new, 1)

    text = once(text, "using FNLfloat = System.Single;\n", "using FNLfloat = System.Double;\n")
    # Suffix with d (not strip) so integer-valued literals such as 1f stay floating point: 1f / 3 must not become 1 / 3.
    text = FLOAT_LITERAL.sub(lambda m: m.group(1) + "d", text)
    text = FLOAT_KEYWORD.sub("double", text)
    if FLOAT_KEYWORD.search(text) or FLOAT_LITERAL.search(text):
        raise ValueError("float residue after port")
    anchor = "// https://github.com/Auburn/FastNoiseLite\n"
    text = once(text, anchor, anchor +
                "//\n"
                "// Vendored by Shooter (ADR-075 / T092) from tag " + UPSTREAM_TAG + ", upstream SHA-256\n"
                "// " + UPSTREAM_SHA256 + ".\n"
                "// Generated by Tools/port_fastnoiselite_double.py: mechanical float -> double port (float keywords,\n"
                "// f-suffixed literals, FNLfloat alias) for cross-runtime determinism, plus this note, `#nullable disable`\n"
                "// and the namespace wrapper. Do not hand-edit; change the script and regenerate.\n"
                "#nullable disable\n")
    text = once(text, "public class FastNoiseLite\n", "namespace " + NAMESPACE + "\n{\npublic class FastNoiseLite\n")
    text = text.rstrip("\n") + "\n}\n"
    return text.encode("utf-8")


def main(argv):
    if len(argv) not in (2, 3) or (len(argv) == 3 and argv[2] != "--check"):
        print(__doc__)
        return 2
    ported = port(Path(argv[1]).read_bytes())
    if len(argv) == 3:
        if TARGET.read_bytes() != ported:
            print("FAIL: vendored FastNoiseLite.cs differs from the scripted port")
            return 1
        print("PASS: vendored FastNoiseLite.cs matches the scripted port; sha256 " + hashlib.sha256(ported).hexdigest())
        return 0
    TARGET.write_bytes(ported)
    print("Wrote " + str(TARGET.relative_to(ROOT)) + " sha256 " + hashlib.sha256(ported).hexdigest())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
